"""Build frontend/data.ja.js from the EN dataset structure + Japanese translations.

Entries without a Japanese translation yet keep their English text (reported).
"""
import copy, glob, json, os, re, sys

ROOT = os.path.dirname(os.path.abspath(__file__))
FE = os.path.join(ROOT, "..", "frontend")


def load(path):
    s = open(path, encoding="utf-8").read()
    return json.loads(s[s.index("{"): s.rindex("}") + 1])


ko = load(os.path.join(FE, "data.js"))
en = load(os.path.join(FE, "data.en.js"))
labels = json.load(open(os.path.join(ROOT, "ja-labels-in.json"), encoding="utf-8"))
cats_ja = open(os.path.join(ROOT, "categories-ja.txt"), encoding="utf-8").read().rstrip("\n").split("\n")
assert len(cats_ja) == len(labels["categories"]), (len(cats_ja), len(labels["categories"]))
CAT = dict(zip(labels["categories"].keys(), cats_ja))
EVIDENCE = {
    "공개 자료 확인": "公開資料で確認",
    "복수 자료 대조": "複数の資料で照合",
    "일반 지식 기반 · 외부 출처 미첨부": "一般的な知識に基づく · 外部出典なし",
}
KIND = {"전문 용어": "専門用語", "현장 표현": "現場の表現"}
FIELDS = {
    "marketing": "マーケティング・広告", "dev": "開発・IT", "fashion": "ファッション・繊維",
    "film": "映像・撮影", "design": "デザイン", "hrfinance": "人事・財務", "common": "業務共通",
}

ja = {}
for p in sorted(glob.glob(os.path.join(ROOT, "ja-out", "*.json"))):
    for row in json.load(open(p, encoding="utf-8")):
        ja[row["id"]] = row

out = copy.deepcopy(en)
out["lang"] = "ja"
for f in out["fields"]:
    f["name"] = FIELDS[f["id"]]
ko_by_id = {e["id"]: e for e in ko["entries"]}
missing = []
for e in out["entries"]:
    k = ko_by_id[e["id"]]
    e["kind"] = KIND[k["kind"]]
    e["category"] = CAT[k["category"]]
    e["evidence"] = EVIDENCE[k["evidence"]]
    t = ja.get(e["id"])
    if not t:
        missing.append(e["id"])
        continue
    for key in ("term", "definition", "example"):
        e[key] = t[key]
    e["aliases"] = [a for a in t.get("aliases", []) if a]
    if k.get("note"):
        e["note"] = t.get("note") or e["note"]

hangul = re.compile(r"[가-힣]")
leaks = [e["id"] for e in out["entries"] if e["id"] in ja and any(hangul.search(str(e[k])) for k in ("term", "definition", "example"))]

with open(os.path.join(FE, "data.ja.js"), "w", encoding="utf-8") as fh:
    fh.write("/* Generated by i18n-work/assemble_ja.py. Japanese dictionary. */\n")
    fh.write("window.WORD_DATA_JA = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")

print(f"entries {len(out['entries'])} translated {len(out['entries']) - len(missing)} missing {len(missing)} hangul-leaks {len(leaks)}")
if leaks:
    print("leaks:", leaks[:20])
sys.exit(0)
